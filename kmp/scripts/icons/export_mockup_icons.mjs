#!/usr/bin/env node
// Dev-only (not part of scripts/check.sh): exports the Retro-cosmos (NASA-punk) icon paths of the
// approved v2 mockup to Compose vector resources (D§3.4).
//
//   node kmp/scripts/icons/export_mockup_icons.mjs [path/to/m10-mockups.html]
//
// The mockup lives in the mission folder, not in this repo; pass its path or set GT_MOCKUPS_HTML.
// Each icon is [shape, detail]; both become stroked paths. The v2 render's yellow corner dot is
// decoration added by the mockup page, not part of `I`, so it is never exported.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '../../shared/src/commonMain/composeResources/drawable');
const source = process.argv[2] ?? process.env.GT_MOCKUPS_HTML;
if (!source) {
  console.error('usage: export_mockup_icons.mjs <m10-mockups.html> (or set GT_MOCKUPS_HTML)');
  process.exit(2);
}

// Mockup icon name -> resource name (gt_ic_<name>.xml).
const NAMES = {
  drop: 'drop', fert: 'fert', pot: 'pot', scissors: 'scissors', sun: 'sun', cal: 'cal',
  camera: 'camera', smartcam: 'smartcam', diag: 'diag', species: 'species', journal: 'journal',
  photo: 'photo', loc: 'loc', edit: 'edit', check: 'check', close: 'close', leaf: 'leaf',
  back: 'back', chev: 'chev', plus: 'plus', lock: 'lock',
};

const html = readFileSync(source, 'utf8');
const helper = html.match(/const c=\(x,y,r\)=>`[^`]*`;/);
const icons = html.match(/const I=\{[\s\S]*?\n\};/);
if (!helper || !icons) {
  console.error('could not find the `c` helper or the `I` icon object in ' + source);
  process.exit(1);
}
const sandbox = {};
vm.runInNewContext(`${helper[0]}\n${icons[0]}\nthis.I = I;`, sandbox);
const I = sandbox.I;

// Round float noise from the arc helper (e.g. 6.5-2.8) to 4 decimals.
const tidy = (d) => d.replace(/-?\d*\.\d+|-?\d+/g, (n) => String(Number(Number(n).toFixed(4))));

const pathXml = (d, filled) => [
  '    <path',
  `        android:pathData="${tidy(d)}"`,
  ...(filled ? ['        android:fillColor="#FF000000"'] : []),
  '        android:strokeWidth="1.5"',
  '        android:strokeColor="#FF000000"',
  '        android:strokeLineCap="butt"',
  '        android:strokeLineJoin="miter" />',
].join('\n');

const vectorXml = (paths) => [
  '<?xml version="1.0" encoding="utf-8"?>',
  '<!-- Generated by kmp/scripts/icons/export_mockup_icons.mjs from the approved v2 mockup. Do not edit by hand. -->',
  '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
  '    android:width="24dp"',
  '    android:height="24dp"',
  '    android:viewportWidth="24"',
  '    android:viewportHeight="24">',
  ...paths,
  '</vector>',
  '',
].join('\n');

mkdirSync(outDir, { recursive: true });
const written = [];
const write = (name, paths) => {
  const file = join(outDir, `gt_ic_${name}.xml`);
  writeFileSync(file, vectorXml(paths));
  written.push(`gt_ic_${name}.xml`);
};

for (const [key, name] of Object.entries(NAMES)) {
  const glyph = I[key];
  if (!glyph) {
    console.error(`icon ${key} is missing in the mockup`);
    process.exit(1);
  }
  const [shape, detail] = glyph;
  write(name, [shape, detail].filter(Boolean).map((d) => pathXml(d, false)));
}
// The water button needs a solid drop: the shape filled and stroked in the tint, without the
// highlight line (it would vanish in the same colour anyway).
write('drop_filled', [pathXml(I.drop[0], true)]);

console.log(`wrote ${written.length} icons to ${outDir}`);
